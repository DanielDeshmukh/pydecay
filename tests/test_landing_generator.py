"""Tests for landingpage/scripts/generate_decay_nuclides.py."""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "landingpage" / "scripts" / "generate_decay_nuclides.py"


@pytest.fixture(scope="module")
def gen():
    spec = importlib.util.spec_from_file_location("generate_decay_nuclides", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# --- time_unit -------------------------------------------------------------


def test_time_unit_sub_day_uses_hours(gen):
    unit, per_unit, display = gen.time_unit(0.250281)
    assert unit == "hours"
    assert per_unit == pytest.approx(1 / 24)
    assert display == "6.007 hours"


def test_time_unit_boundary_exactly_one_day_uses_days(gen):
    unit, per_unit, display = gen.time_unit(1.0)
    assert unit == "days"
    assert per_unit == 1.0
    assert display == "1 days"


def test_time_unit_just_under_one_day_uses_hours(gen):
    unit, _, _ = gen.time_unit(0.9999)
    assert unit == "hours"


def test_time_unit_icrp107_iodine131(gen):
    days = 692988.48 / 86400.0
    unit, _, display = gen.time_unit(days)
    assert unit == "days"
    assert display == "8.0207 days"


def test_time_unit_half_year_boundary(gen):
    year_half = 365.2422 / 2
    assert gen.time_unit(year_half - 0.1)[0] == "days"
    assert gen.time_unit(year_half + 0.1)[0] == "years"


def test_time_unit_years_display_and_days_per_unit(gen):
    unit, per_unit, display = gen.time_unit(1925.23)
    assert unit == "years"
    assert per_unit == 365.2422
    assert display == "5.271 years"


def test_time_unit_geologic_years_avoids_e_plus_notation(gen):
    unit, _, display = gen.time_unit(4.468e9 * 365.2422)
    assert unit == "years"
    assert "e+0" not in display
    assert "years" in display



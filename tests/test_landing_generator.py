# --- build_rows ------------------------------------------------------------


@pytest.fixture(scope="module")
def rows(gen):
    return gen.build_rows()


def test_build_rows_cardinality_between_demo_and_full_catalog(gen, rows):
    assert 1200 <= len(rows) <= 1400


def test_build_rows_sorted_and_unique(rows):
    ids = [row.id for row in rows]
    assert ids == sorted(ids)
    assert len(set(ids)) == len(ids)


def test_build_rows_excludes_stable_endpoints(rows):
    ids = {row.id for row in rows}
    assert "Ag-107" not in ids  # stable in ICRP-107, half_life_s == inf
    assert "I-131" in ids


def test_build_rows_icrp107_iodine131_days(rows):
    i131 = next(row for row in rows if row.id == "I-131")
    assert i131.days == pytest.approx(692988.48 / 86400.0)
    assert i131.element == "Iodine"
    assert i131.time_unit == "days"
    assert i131.days_per_unit == 1.0


def test_build_rows_all_ids_parse_and_symbols_resolve(gen, rows):
    for row in rows:
        match = gen._ID_RE.match(row.id)
        assert match is not None, row.id
        assert match.group(1) in gen.SYMBOL_NAMES, row.id
        assert row.element == gen.SYMBOL_NAMES[match.group(1)]


def test_build_rows_all_values_finite_and_positive(rows):
    for row in rows:
        assert row.days > 0
        assert row.days_per_unit > 0
        assert row.display and row.element


def test_build_rows_technetium99m_is_hours(rows):
    tc99m = next(row for row in rows if row.id == "Tc-99m")
    assert tc99m.time_unit == "hours"
    assert tc99m.days < 1


def test_build_rows_uranium238_is_years(rows):
    u238 = next(row for row in rows if row.id == "U-238")
    assert u238.time_unit == "years"
    assert u238.days > 365.2422


# --- render / output_path / main ------------------------------------------


def test_render_header_and_import(gen, rows):
    source = gen.render(rows[:5])
    assert source.startswith("// GENERATED by landingpage/scripts/generate_decay_nuclides.py")
    assert 'import type { DemoNuclide } from "./nuclides";' in source
    assert source.endswith("];\n")


def test_render_contains_every_row_exactly_once(gen, rows):
    source = gen.render(rows)
    assert source.count("    id: ") == len(rows)
    for row in rows:
        assert f'id: "{row.id}"' in source


def test_render_never_emits_python_float_sentinels(gen, rows):
    source = gen.render(rows)
    for sentinel in ("inf", "None", "nan"):
        assert not re.search(rf"\b{sentinel}\b", source)


def test_fmt_float_normalizes_python_exponents(gen):
    assert gen.fmt_float(5.324074074074074e-05) == "5.324074074074074e-5"
    assert gen.fmt_float(1.1574074074074074e-09) == "1.1574074074074074e-9"
    assert gen.fmt_float(2.812425e18) == "2.812425e18"
    assert gen.fmt_float(1.0) == "1.0"
    assert gen.fmt_float(365.2422) == "365.2422"
    assert gen.fmt_float(0.041666666666666664) == "0.041666666666666664"


def test_render_uses_js_exponent_style_everywhere(gen, rows):
    """Prettier rewrites e-05/e+18 to e-5/e18; emit the prettier-stable form.

    Display strings are exempt: prettier never touches string contents.
    """
    source = gen.render(rows)
    for line in source.splitlines():
        stripped = line.strip()
        if stripped.startswith(("halfLifeDays:", "daysPerUnit:")):
            assert "e+" not in line, line
            assert not re.search(r"e-0\d", line), line


def test_render_is_deterministic(gen, rows):
    assert gen.render(rows) == gen.render(rows)


def test_output_path_points_at_expected_file(gen):
    path = gen.output_path()
    assert path.name == "decayNuclides.ts"
    assert path.parent == ROOT / "landingpage" / "src" / "data"


def test_committed_file_is_fresh(gen, rows):
    """The checked-in decayNuclides.ts must match a fresh render."""
    on_disk = gen.output_path().read_text(encoding="utf-8")
    assert on_disk == gen.render(rows)
